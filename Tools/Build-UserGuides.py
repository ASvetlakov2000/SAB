    for i, scenario in enumerate(guide['scenarios']):
        title, items, *operation = scenario
        marker = f' data-operation="{operation[0]}"' if operation else ''
        introduction = f'<p>{e(items[0])}</p>' if operation else ''
        action_items = items[1:] if operation else items
        scenarios += f'<details class="content-card" id="scenario-{i + 1}"{marker}><summary><strong>{e(title)}</strong></summary>{introduction}{steps_html(action_items)}</details>\n'
