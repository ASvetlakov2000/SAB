def steps_html(items):
    return '<ol class="steps">' + ''.join(f'<li><span class="step-text">{e(s)}</span></li>' for s in items) + '</ol>'


def section(id_, title, body, soft=False):
    return f'<section class="section{" section--soft" if soft else ""}" id="{id_}"><div class="section__inner"><h2>{e(title)}.</h2><div class="content-stack">{body}</div></div></section>\n'


