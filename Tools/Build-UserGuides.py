# Library descriptions and prerequisites come from the same operation catalog as
# the actual window. Button labels come from XAML, not from retired ribbon names.
library_cs = (ROOT / 'SAB/Cls_RevitLibraryBuilder/UI/LibraryBuilderWindow.cs').read_text(encoding='utf-8-sig')
library_xml = ET.parse(ROOT / 'SAB/Cls_RevitLibraryBuilder/UI/LibraryBuilderWindow.xaml')
buttons = {}
for node in library_xml.iter():
    name = node.attrib.get('{http://schemas.microsoft.com/winfx/2006/xaml}Name')
    if name:
        labels = [n.attrib['Text'] for n in node.iter() if n.tag.endswith('TextBlock') and 'Text' in n.attrib]
        if labels:
            buttons[name] = labels[0]
pattern = r'CreateInfo\(LibraryToolId\.(\w+),\s*' + r',\s*'.join([r'"((?:[^"\\]|\\.)*)"'] * 6)
OPERATIONS = {}
MODES = dict(Catalogs='Каталоги', Naming='Наименования', Graphics='Графика и превью', Placement='Размещение и очистка')
for match in re.finditer(pattern, library_cs):
    key, mode, button, title, description, requirement, instruction = match.groups()
    instruction = instruction.replace('Excel или LibreOffice', 'редакторе таблиц')
    instruction = instruction.replace('вид категории Легенда', 'вид «Легенда»')
    steps = [re.sub(r'^\d+\.\s*', '', s) for s in instruction.split(r'\n')]
    OPERATIONS[key] = (MODES[mode], buttons[button], title, description, requirement, steps)


def library(slug, title, intro, keys, prepare, check, errors):
    scenarios = []
    for key in keys:
        mode, button, operation, description, requirement, steps = OPERATIONS[key]
        # Preparation precedes opening the operation; saving an import table
        # precedes choosing the file. Availability is checked on window opening.
        prepare_count = 1 if steps[0].startswith(('Откройте', 'Подготовьте', 'Проверьте', 'Сначала', 'Выгрузите', 'Выберите только')) else 0
        if key in ('ImportTypeNaming', 'ImportMaterialNaming', 'DeleteSelectedTypesAndFamilies'):
            prepare_count = 2
        body = [description + ' Перед запуском: ' + requirement + '.'] + steps[:prepare_count] + [
                f'В окне «Библиотека» выберите «{mode}», затем карточку «{button}». Нажмите «Запустить».'] + steps[prepare_count:]
        scenarios.append((operation, body, key))
    add(slug, title, 'Библиотека', intro, prepare,
        ['Откройте модель, с которой будете работать. Для изменения данных сначала сохраните её копию.',
         'Нажмите SAB → Библиотека → Библиотека.',
         'Раскройте ниже нужный сценарий. Выберите указанный режим и карточку операции; затем нажмите «Запустить».',
         'Выполните запросы выбора файла, папки или элементов. Дождитесь результата и прочитайте сообщения о пропусках.',
         'Проверьте созданные файлы или изменённые элементы по пунктам «Проверка результата».'],
        check, errors, scenarios)

